
import psycopg
from dotenv import dotenv_values

DATABASE_URL = dotenv_values(".env").get("DATABASE_URL")

if not DATABASE_URL:
    raise SystemExit("DATABASE_URL not found in .env")

with psycopg.connect(DATABASE_URL, connect_timeout=15) as conn:
    with conn.cursor() as cur:

        cur.execute("""
            CREATE TABLE IF NOT EXISTS agents (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                api_key_hash TEXT UNIQUE NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS usage_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                agent_id BIGINT NOT NULL REFERENCES agents(id),
                endpoint TEXT NOT NULL,
                billable BOOLEAN NOT NULL DEFAULT FALSE,
                request_id TEXT,
                barcode TEXT,
                response_json JSONB,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        cur.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_usage_agent_request
            ON usage_events (agent_id, request_id)
            WHERE request_id IS NOT NULL
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS demo_billing_ledger (
                usage_event_id BIGINT PRIMARY KEY REFERENCES usage_events(id),
                agent_id BIGINT NOT NULL REFERENCES agents(id),
                amount_micro_usd BIGINT NOT NULL,
                status TEXT NOT NULL DEFAULT 'simulation',
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        for table in ("agents", "usage_events", "demo_billing_ledger"):
            cur.execute(f"SELECT COUNT(*) FROM {table}")
            count = cur.fetchone()[0]
            print(f"{table}: {count} records")

print("PASS: AgentPrice cloud tables ready!")
